#!/usr/bin/env python3
"""Generate src/domain/SolarTerms.cpp from test/fixtures/solar_terms_2026_2028.json.

The fixture is the public response of the KASI 특일 정보 API
(B090041/SpcdeInfoService/get24DivisionsInfo, solYear=YYYY) captured on
2026-11-11 (dateName + locdate only, no key). The firmware ships it as a constant
table, so the calendar tab needs no runtime request for 24절기.

Usage: python tools/gen_solar_terms.py [--check]
"""

import json
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "test", "fixtures", "solar_terms_2026_2028.json")
OUT = os.path.join(ROOT, "src", "domain", "SolarTerms.cpp")
NAMES = [
    "소한",
    "대한",
    "입춘",
    "우수",
    "경칩",
    "춘분",
    "청명",
    "곡우",
    "입하",
    "소만",
    "망종",
    "하지",
    "소서",
    "대서",
    "입추",
    "처서",
    "백로",
    "추분",
    "한로",
    "상강",
    "입동",
    "소설",
    "대설",
    "동지",
]


def build() -> str:
    data = json.load(open(SRC, encoding="utf-8"))
    rows = []
    for year in sorted(data, key=int):
        items = data[year]
        if len(items) != 24:
            raise SystemExit("year %s: expected 24 terms, got %d" % (year, len(items)))
        for name, locdate in items:
            if name not in NAMES:
                raise SystemExit("unknown term name: %s" % name)
            if not str(locdate).startswith(year):
                raise SystemExit("date %s not in year %s" % (locdate, year))
            d = str(locdate)
            rows.append((int(year), int(d[4:6]), int(d[6:8]), NAMES.index(name)))
    rows.sort()
    lines = [
        '#include "SolarTerms.h"',
        "",
        "// GENERATED by tools/gen_solar_terms.py from test/fixtures/solar_terms_2026_2028.json",
        "// (KASI SpcdeInfoService/get24DivisionsInfo, captured 2026-11-11). Do not edit by hand.",
        "namespace kdash {",
        "namespace terms {",
        "namespace {",
        "constexpr const char* kNames[24] = {%s};"
        % ", ".join('"%s"' % n for n in NAMES),
        "constexpr Term kTerms[] = {",
    ]
    lines += ["    {%d, %d, %d, %d}," % r for r in rows]
    lines += [
        "};",
        "constexpr size_t kCount = sizeof(kTerms) / sizeof(kTerms[0]);",
        "}  // namespace",
        "",
        "size_t Count() { return kCount; }",
        "const Term& At(size_t i) { return kTerms[i < kCount ? i : 0]; }",
        'const char* Name(int index) { return index >= 0 && index < 24 ? kNames[index] : ""; }',
        "",
        "}  // namespace terms",
        "}  // namespace kdash",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        cur = (
            open(OUT, encoding="utf-8", newline="").read().replace("\r\n", "\n")
            if os.path.exists(OUT)
            else ""
        )
        if cur != text:
            print("SolarTerms.cpp is out of date; run tools/gen_solar_terms.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
