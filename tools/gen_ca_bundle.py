#!/usr/bin/env python3
"""Generate src/net/CaBundle.h — pinned root CAs for the allowlisted API hosts.

Roots are copied verbatim from the Mozilla-derived `certifi` bundle (no
network needed). With --verify the script additionally connects to every
allowlisted host and checks that the presented chain ends at one of the
pinned roots (needs network; uses the OS/certifi trust store, never insecure).

Usage:
  python tools/gen_ca_bundle.py            # regenerate header
  python tools/gen_ca_bundle.py --verify   # + live chain check
"""

import argparse
import datetime
import hashlib
import os
import re
import socket
import ssl
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.join(ROOT, "src", "net", "CaBundle.h")

# host:port -> root CA common name (observed 2026-11-02 with openssl s_client)
HOSTS = {
    ("apis.data.go.kr", 443): "GlobalSign Root CA - R3",
    ("oapi.koreaexim.go.kr", 443): "DigiCert Global Root G2",
    ("openapi.koreainvestment.com", 9443): "USERTrust RSA Certification Authority",
}


def load_roots():
    import certifi  # noqa: WPS433 (dev-only dependency)

    pem = open(certifi.where(), encoding="utf-8").read()
    out = {}
    for name in sorted(set(HOSTS.values())):
        m = re.search(
            r"# Issuer: [^\n]*" + re.escape(name) + r"[^\n]*\n.*?"
            r"(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)",
            pem,
            re.S,
        )
        if not m:
            raise SystemExit("root not found in certifi: %s" % name)
        out[name] = m.group(1).strip()
    return out, getattr(certifi, "__version__", "?")


def fingerprint(pem: str) -> str:
    der = ssl.PEM_cert_to_DER_cert(pem)
    return hashlib.sha256(der).hexdigest()


def verify(roots) -> int:
    ctx = ssl.create_default_context(cafile=None)
    bad = 0
    for (host, port), root in HOSTS.items():
        try:
            with socket.create_connection((host, port), timeout=15) as s:
                with ctx.wrap_socket(s, server_hostname=host) as t:
                    chain = (
                        t.get_verified_chain()
                        if hasattr(t, "get_verified_chain")
                        else None
                    )
            if chain:
                top = chain[-1]
                top_pem = ssl.DER_cert_to_PEM_cert(
                    top if isinstance(top, bytes) else top.public_bytes()
                )
                ok = fingerprint(top_pem) == fingerprint(roots[root])
            else:
                ok = True  # handshake verified; chain API unavailable
            print("%-32s %-5d %s %s" % (host, port, "OK " if ok else "MISMATCH", root))
            bad += 0 if ok else 1
        except Exception as e:  # report, never bypass verification
            print("%-32s %-5d FAIL %s" % (host, port, e))
            bad += 1
    return bad


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--verify", action="store_true")
    a = ap.parse_args()
    roots, ver = load_roots()
    lines = [
        "#pragma once",
        "// GENERATED by tools/gen_ca_bundle.py — do not edit by hand.",
        "// Pinned root CAs for net::kAllowHosts (TLS-01: verification is",
        "// mandatory; setInsecure() is forbidden). Source: certifi %s" % ver,
        "// (Mozilla CA list), generated %s." % datetime.date.today().isoformat(),
    ]
    for (host, port), root in HOSTS.items():
        lines.append("//   %s:%d -> %s" % (host, port, root))
    lines += [
        "",
        "namespace kdash {",
        "namespace net {",
        "",
        "inline constexpr const char kCaBundlePem[] =",
    ]
    for name, pem in roots.items():
        lines.append("    // %s sha256=%s" % (name, fingerprint(pem)))
        for row in pem.splitlines():
            lines.append('    "%s\\n"' % row)
    lines[-1] += ";"
    lines += ["", "}  // namespace net", "}  // namespace kdash", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d roots)" % (os.path.relpath(OUT, ROOT), len(roots)))
    return verify(roots) if a.verify else 0


if __name__ == "__main__":
    sys.exit(main())
