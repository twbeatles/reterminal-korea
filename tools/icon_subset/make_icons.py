#!/usr/bin/env python3
"""Icon bitmap generator: Material Symbols Outlined TTF -> 1bpp C arrays.

Usage:
  curl -L -o build/icons/MaterialSymbolsOutlined.ttf \\
    "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.ttf"
  python tools/icon_subset/make_icons.py \\
      --ttf build/icons/MaterialSymbolsOutlined.ttf --out src/ui/icons/IconData.h

Notes:
  - Apache-2.0 (google/material-design-icons). The TTF itself is never
    committed (build/ is gitignored); src/ui/icons/LICENSE-Apache-2.0.txt
    keeps the license text. The input is pinned by sha256.
  - The generated header is the single source of truth for `IconId`; the
    order of ICONS below is the enum order.
  - Raster: variable axes FILL 0 / GRAD 0 / opsz clamp(size,20,48) / wght 600,
    glyph centered in a size x size box, threshold 128, MSB-first rows.
    Deterministic: same input bytes -> same output bytes.
"""

import argparse
import hashlib
import sys
from pathlib import Path

TTF_SHA256 = "f7837ba8573d9a7a74931618ced8307bc81f96d49af296bf6c8052c772ed5282"
WEIGHT = 600
SIZES = (24, 64)

# (IconId name, codepoint, also rendered at 64px)
ICONS = [
    ("Sun", 0xE81A, True),  # sunny
    ("PartlyCloudy", 0xF172, True),  # partly_cloudy_day
    ("Cloud", 0xF15C, True),  # cloud
    ("Rain", 0xF176, True),  # rainy (also 소나기)
    ("Snow", 0xE2CD, True),  # weather_snowy
    ("RainSnow", 0xF60B, True),  # weather_mix
    ("Unknown", 0xE8FD, True),  # help
    ("Usd", 0xE227, True),  # attach_money
    ("Jpy", 0xEAFB, True),  # currency_yen
    ("Humidity", 0xF87E, False),  # humidity_percentage
    ("Umbrella", 0xF1AD, False),  # umbrella
    ("Air", 0xEFD8, False),  # air
    ("Home", 0xE9B2, False),  # home
    ("FxExchange", 0xEB70, False),  # currency_exchange
    ("Chart", 0xE6E1, False),  # show_chart
    ("Store", 0xEA12, False),  # storefront
    ("Wifi", 0xE63E, False),  # wifi
    ("WifiOff", 0xE648, False),  # wifi_off
    ("BatteryFull", 0xF304, False),  # battery_android_full
    ("BatteryMid", 0xF30A, False),  # battery_android_3
    ("BatteryLow", 0xF30C, False),  # battery_android_1
    ("BatteryCharging", 0xF305, False),  # battery_android_bolt
    ("Clock", 0xEFD6, False),  # schedule
    ("Sync", 0xE627, False),  # sync
    ("Thermometer", 0xE1FF, False),  # device_thermostat (observed temp head)
    ("Device", 0xE30D, False),  # developer_board (device status head)
    ("Warning", 0xF083, False),  # warning (low battery / safe mode notice)
]


def raster(font, cp, size):
    from PIL import Image, ImageDraw

    img = Image.new("L", (size, size), 0)
    d = ImageDraw.Draw(img)
    ch = chr(cp)
    x0, y0, x1, y1 = d.textbbox((0, 0), ch, font=font)
    if x1 <= x0 or y1 <= y0:
        raise SystemExit("empty glyph U+%04X at %dpx" % (cp, size))
    d.text(
        ((size - (x1 - x0)) // 2 - x0, (size - (y1 - y0)) // 2 - y0),
        ch,
        font=font,
        fill=255,
    )
    px = img.load()
    out = bytearray()
    for y in range(size):
        for bx in range((size + 7) // 8):
            byte = 0
            for bit in range(8):
                x = bx * 8 + bit
                if x < size and px[x, y] >= 128:
                    byte |= 0x80 >> bit
            out.append(byte)
    if not any(out):
        raise SystemExit("blank raster U+%04X at %dpx" % (cp, size))
    return bytes(out)


def build(ttf_path):
    from PIL import ImageFont

    fonts = {}
    for size in SIZES:
        f = ImageFont.truetype(str(ttf_path), size)
        f.set_variation_by_axes([0, 0, min(48, max(20, size)), WEIGHT])
        fonts[size] = f
    data = {}
    for name, cp, large in ICONS:
        for size in SIZES:
            if size == 64 and not large:
                continue
            data[(name, size)] = raster(fonts[size], cp, size)
    return data


def emit(data):
    total = sum(len(b) for b in data.values())
    lines = [
        "// Auto-generated by tools/icon_subset/make_icons.py — do not edit.",
        "// Icons: Material Symbols Outlined (google/material-design-icons),",
        "// Apache-2.0. See LICENSE-Apache-2.0.txt in this directory.",
        "// Input SHA256: %s" % TTF_SHA256,
        "// axes FILL=0 GRAD=0 wght=%d; sizes=%s; bitmap=%d bytes"
        % (WEIGHT, "/".join(str(s) for s in SIZES), total),
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace kdash {",
        "namespace ui {",
        "",
        "enum class IconId : uint8_t { None, %s, Count };"
        % ", ".join(n for n, _c, _l in ICONS),
        "",
        "namespace icondata {",
        "",
    ]
    for size in SIZES:
        for name, cp, _l in ICONS:
            bits = data.get((name, size))
            if bits is None:
                continue
            lines.append("// U+%04X" % cp)
            lines.append("static const uint8_t kI%d_%s[] = {" % (size, name))
            for i in range(0, len(bits), 16):
                lines.append(
                    "  " + ", ".join("0x%02X" % b for b in bits[i : i + 16]) + ","
                )
            lines.append("};")
        lines.append("")
    for size in SIZES:
        lines.append(
            "// size x size, stride (size+7)/8, MSB-first, 1=black; "
            "nullptr = not available at this size."
        )
        lines.append("static const uint8_t* const k%d[] = {" % size)
        lines.append("  nullptr,  // None")
        for name, _c, _l in ICONS:
            ref = ("kI%d_%s" % (size, name)) if (name, size) in data else "nullptr"
            lines.append("  %s,  // %s" % (ref, name))
        lines.append("};")
        lines.append(
            "static_assert(sizeof(k%d) / sizeof(k%d[0]) == (int)IconId::Count,"
            ' "icon table size");' % (size, size)
        )
        lines.append("")
    lines += [
        "}  // namespace icondata",
        "}  // namespace ui",
        "}  // namespace kdash",
        "",
    ]
    return "\n".join(lines), total


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    raw = Path(a.ttf).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != TTF_SHA256:
        print(
            "refusing: input sha256 %s != pinned %s" % (digest, TTF_SHA256),
            file=sys.stderr,
        )
        return 3
    try:
        import PIL  # noqa: F401
    except ImportError:
        print("need Pillow: pip install pillow", file=sys.stderr)
        return 2
    text, total = emit(build(a.ttf))
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(text.encode("utf-8"))
    print(
        "icon-report: icons=%d bitmap=%dB sha=%s"
        % (len(ICONS), total, hashlib.sha256(text.encode("utf-8")).hexdigest()[:16])
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
